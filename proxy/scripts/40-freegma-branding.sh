#!/bin/sh
# Freegma: render branding assets and nginx filter snippets before nginx starts.
# Runs from the official nginx image's /docker-entrypoint.d hook (after the
# template envsubst step, before nginx itself is started).
set -eu

log() { echo "freegma: $*"; }

is_true() {
    case "$(echo "${1:-}" | tr '[:upper:]' '[:lower:]')" in
        1|true|yes|on) return 0 ;;
        *) return 1 ;;
    esac
}

DEFAULT_DIR=/usr/share/freegma/branding-default
BRANDING_DIR="${FREEGMA_BRANDING_DIR:-/etc/freegma/branding}"
STATIC_DIR=/usr/share/freegma/www-static
WWW=/var/lib/freegma/www
CONF=/etc/nginx/freegma
BRAND="${FREEGMA_BRAND_NAME:-Freegma}"
case "$BRAND" in
    *'$'*) echo "freegma: warning: '\$' is not allowed in FREEGMA_BRAND_NAME, removing it"
           BRAND="$(printf '%s' "$BRAND" | tr -d '$')" ;;
esac

mkdir -p "$WWW" "$CONF"
rm -rf "${WWW:?}"/*

# A file in the mounted branding dir wins over the built-in default.
pick() {
    if [ -f "$BRANDING_DIR/$1" ]; then
        echo "$BRANDING_DIR/$1"
    elif [ -f "$DEFAULT_DIR/$1" ]; then
        echo "$DEFAULT_DIR/$1"
    fi
}

if [ -d "$BRANDING_DIR" ] && [ -n "$(ls -A "$BRANDING_DIR" 2>/dev/null)" ]; then
    log "branding: $BRANDING_DIR (missing files fall back to built-in defaults)"
else
    log "branding: built-in defaults"
fi

# ---- 1. static branding files ----------------------------------------------------
for f in logo.svg logo-icon.svg favicon.svg favicon.png apple-touch-icon.png freegma.css; do
    src="$(pick "$f")"
    if [ -n "$src" ]; then
        cp "$src" "$WWW/$f"
    else
        log "warning: branding file '$f' not found"
    fi
done
cp "$STATIC_DIR"/* "$WWW/"
cp /usr/share/freegma/LICENSE /usr/share/freegma/NOTICE.md "$WWW/" 2>/dev/null || true

# Login illustration: first match wins; replaces Penpot's login artwork.
login_conf="$CONF/login-illustration.conf"
echo "# generated by 40-freegma-branding.sh" > "$login_conf"
for ext in svg webp png jpg; do
    src="$(pick "login-illustration.$ext")"
    [ -n "$src" ] || continue
    cp "$src" "$WWW/login-illustration.$ext"
    case "$ext" in
        svg) mime=image/svg+xml ;; webp) mime=image/webp ;; png) mime=image/png ;; jpg) mime=image/jpeg ;;
    esac
    cat > "$login_conf" <<EOF
# generated by 40-freegma-branding.sh
location = /images/registration-illustration.png {
    alias $WWW/login-illustration.$ext;
    types { }
    default_type $mime;
    add_header Cache-Control "public, max-age=300" always;
}
EOF
    break
done

# ---- 2. accent colours from env (optional; override freegma.css) -----------------
if [ -n "${FREEGMA_ACCENT_DARK:-}" ]; then
    printf '\n.default{--color-accent-primary:%s;--freegma-accent:%s}\n' \
        "$FREEGMA_ACCENT_DARK" "$FREEGMA_ACCENT_DARK" >> "$WWW/freegma.css"
fi
if [ -n "${FREEGMA_ACCENT_LIGHT:-}" ]; then
    printf '\n.light{--color-accent-primary:%s;--freegma-accent:%s}\n' \
        "$FREEGMA_ACCENT_LIGHT" "$FREEGMA_ACCENT_LIGHT" >> "$WWW/freegma.css"
fi

# ---- 3. runtime config for freegma.js ------------------------------------------------
# JSON string encoder (no jq in the image): escapes \ " TAB, joins lines with \n.
json_file() {
    printf '"'
    sed -e 's/\r$//' -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/\t/\\t/g' "$1" \
        | awk 'BEGIN{ORS=""} {if (NR>1) printf "\\n"; print}'
    printf '"'
}
json_str() {
    tmp="$(mktemp)"; printf '%s' "$1" > "$tmp"; json_file "$tmp"; rm -f "$tmp"
}

show_attr=false
is_true "${FREEGMA_SHOW_ATTRIBUTION:-true}" && show_attr=true

{
    printf '{"name":%s,' "$(json_str "$BRAND")"
    printf '"version":%s,' "$(json_str "${FREEGMA_VERSION:-dev}")"
    printf '"penpotVersion":%s,' "$(json_str "${FREEGMA_PENPOT_VERSION:-}")"
    printf '"sourceUrl":%s,' "$(json_str "${FREEGMA_SOURCE_URL:-}")"
    printf '"showAttribution":%s,' "$show_attr"
    printf '"logo":%s,' "$(json_file "$WWW/logo.svg")"
    printf '"icon":%s}' "$(json_file "$WWW/logo-icon.svg")"
} > "$WWW/config.json"

{
    printf 'window.FREEGMA = '
    cat "$WWW/config.json"
    printf ';\n'
    cat "$STATIC_DIR/freegma.js"
} > "$WWW/freegma.js"

# Cache-buster derived from the rendered content.
HASH="$(cat "$WWW"/* | md5sum | cut -c1-10)"

# ---- 4. nginx: index.html injection ------------------------------------------------
# Escape a value for a single-quoted nginx string.
esc() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e "s/'/\\\\'/g"; }
# Escape a value for an HTML attribute.
html_attr() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/"/\&quot;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }

head_inject="<link rel=\"stylesheet\" href=\"/freegma/freegma.css?v=$HASH\">"
head_inject="$head_inject<link rel=\"icon\" type=\"image/svg+xml\" href=\"/freegma/favicon.svg?v=$HASH\">"
if [ -f "$WWW/apple-touch-icon.png" ]; then
    head_inject="$head_inject<link rel=\"apple-touch-icon\" href=\"/freegma/apple-touch-icon.png?v=$HASH\">"
fi
head_inject="$head_inject<meta name=\"application-name\" content=\"$(html_attr "$BRAND")\">"
head_inject="$head_inject<meta name=\"apple-mobile-web-app-title\" content=\"$(html_attr "$BRAND")\">"
head_inject="$head_inject<script src=\"/freegma/freegma.js?v=$HASH\"></script>"

{
    echo "# generated by 40-freegma-branding.sh"
    printf "sub_filter '</head>' '%s</head>';\n" "$(esc "$head_inject")"
    # Runs synchronously right after Penpot's inline SVG sprite and before the
    # app boots, so the Penpot logo never flashes.
    echo "sub_filter '<div id=\"app\"></div>' '<script>window.freegmaApplyLogos&&window.freegmaApplyLogos();</script><div id=\"app\"></div>';"
} > "$CONF/html-filters.conf"

# ---- 5. nginx: UI text replacements ----------------------------------------------------
text_conf="$CONF/text-filters.conf"
echo "# generated by 40-freegma-branding.sh" > "$text_conf"
TSV="$(pick text-replacements.tsv)"
brand_sed="$(printf '%s' "$BRAND" | sed 's/[&/\\]/\\&/g')"
if is_true "${FREEGMA_REBRAND_TEXT:-true}" && [ -n "$TSV" ]; then
    count=0
    tab="$(printf '\t')"
    # Format: <search><TAB><replacement>; '#' starts a comment; {{BRAND}} = brand name.
    while IFS="$tab" read -r from to || [ -n "$from" ]; do
        case "$from" in ''|'#'*) continue ;; esac
        to="$(printf '%s' "$to" | sed "s/{{BRAND}}/$brand_sed/g")"
        case "$from$to" in
            *'$'*) log "skipping replacement containing '\$': $from"; continue ;;
        esac
        printf "sub_filter '%s' '%s';\n" "$(esc "$from")" "$(esc "$to")" >> "$text_conf"
        count=$((count + 1))
    done < "$TSV"
    log "$count UI text replacements active"
else
    log "UI text replacements disabled"
fi

# ---- 6. nginx: resolver (re-resolve the upstream after container recreation) ------------
RESOLVER="${FREEGMA_RESOLVER:-$(awk '$1=="nameserver"{sub(/%.*$/,"",$2); printf "%s ", ($2 ~ ":") ? "["$2"]" : $2}' /etc/resolv.conf)}"
[ -n "$(echo "$RESOLVER" | tr -d ' ')" ] || RESOLVER=127.0.0.11
echo "resolver $RESOLVER valid=10s ipv6=off;" > "$CONF/resolver.conf"

log "ready: brand='$BRAND' version=${FREEGMA_VERSION:-dev} penpot=${FREEGMA_PENPOT_VERSION:-?} hash=$HASH upstream=${FREEGMA_UPSTREAM}"
